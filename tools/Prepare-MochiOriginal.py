"""Package official OneWorks Bun captures at 466px for the LVGL product renderer.

Run the official export first (tools/avatar-original/README.md). This step only
resamples the transparent 512px capture to the physical display, crops unused
alpha, and converts to LVGL RGB565 + A8. No old artwork or paths are imported.
"""
from pathlib import Path
import hashlib
import json
import subprocess

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "firmware/assets/mochi-original"
SOURCE_COMMIT = "a06ba84c123cf82e2b1a59c36b403392e22f9d08"
COLORS = ("white", "sky", "lavender", "rose", "mint", "honey")


def main():
    revision = subprocess.check_output(
        ["git", "-C", str(ROOT / ".references/oneworks-avatar"), "rev-parse", "HEAD"],
        text=True,
    ).strip()
    if revision != SOURCE_COMMIT:
        raise SystemExit(f"Export source changed: expected {SOURCE_COMMIT}, got {revision}")
    assets = []
    declarations = ["/* Generated by tools/Prepare-MochiOriginal.py. OneWorks MIT, see assets notice. */"]
    bayer = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], dtype=np.uint16)
    for color in COLORS:
        name = "body_" + color
        source = ASSETS / ("body-" + color + ".png")
        definition = json.loads((ASSETS / ("body-" + color + ".definition.json")).read_text(encoding="utf-8"))
        if definition["schema"] != "oneworks.avatar" or definition["version"] != 1:
            raise SystemExit("Expected versioned OneWorks scene")
        if definition["scene"]["decals"]:
            raise SystemExit("The hardware body must not contain decals or third-party marks")
        image = Image.open(source)
        if image.size != (512, 512) or image.mode != "RGBA":
            raise SystemExit("Expected official transparent 512x512 RGBA capture")
        if image.getpixel((0, 0))[3] != 0:
            raise SystemExit("Capture has an opaque camera background")
        scaled = image.resize((466, 466), Image.Resampling.LANCZOS)
        left, top, right, bottom = scaled.getchannel("A").getbbox()
        # Keep a two-pixel transparent safety border for transform filtering.
        left, top, right, bottom = max(0, left-2), max(0, top-2), min(466, right+2), min(466, bottom+2)
        cropped = scaled.crop((left, top, right, bottom))
        pixels = np.asarray(cropped, dtype=np.uint16)
        height, width = pixels.shape[:2]
        yy, xx = np.mgrid[:height, :width]
        threshold = bayer[(yy+top) % 4, (xx+left) % 4] * 16 + 8
        red = (pixels[:, :, 0] * 31 + threshold) // 255
        green = (pixels[:, :, 1] * 63 + threshold) // 255
        blue = (pixels[:, :, 2] * 31 + threshold) // 255
        rgb = ((red << 11) | (green << 5) | blue).astype("<u2").tobytes()
        raw = rgb + pixels[:, :, 3].astype("uint8").tobytes()
        binary = ASSETS / (name + ".rgb565a8")
        binary.write_bytes(raw)
        assets.append(dict(id=name, x=left, y=top, width=width, height=height,
                           binary=binary.name, bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest(),
                           source=source.name, sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest()))
        declarations.append(f'extern const uint8_t original_{name}[] asm("_binary_original_{name}_start");')
    declarations.append("static const original_asset_t original_assets[] = {")
    for asset in assets:
        declarations.append('    {"%s",%d,%d,{.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.w=%d,.h=%d,.stride=%d},.data_size=%d,.data=original_%s}},' % (
            asset["id"], asset["x"], asset["y"], asset["width"], asset["height"], asset["width"] * 2, asset["bytes"], asset["id"]))
    declarations.append("};")
    (ROOT / "firmware/main/mochi_original_index.inc").write_text("\n".join(declarations) + "\n", encoding="utf-8")
    manifest = dict(format="rgb565+a8", physicalCanvas=[466, 466], sourceCanvas=[512, 512],
                    source=dict(repository="https://github.com/oneworks-ai/avatar", commit=revision,
                                version="1.0.0-rc.9", preset="bun", license="MIT"), assets=assets)
    (ASSETS / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    # The preview is the independently reopened official PNG, on the display's
    # actual dark circular surface, at physical pixel resolution.
    display = Image.new("RGBA", (466, 466), "#0d1017")
    display.alpha_composite(Image.open(ASSETS / "avatar.png").convert("RGBA").resize((466, 466), Image.Resampling.LANCZOS))
    display.convert("RGB").save(ASSETS / "preview-466.png")
    print(json.dumps(dict(layers=len(assets), bytes=sum(a["bytes"] for a in assets), sourceCommit=revision, physicalCanvas=466)))


if __name__ == "__main__":
    main()
